import { formatCurrency, formatDate } from './formatters';
import type { Customer, CustomerLedgerEntry } from '../types/customer.types';

const ESCAPES: Record<string, string> = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' };
const escapeHtml = (v: unknown): string => String(v ?? '').replace(/[&<>"']/g, (c) => ESCAPES[c]);
const money = (v: number) => formatCurrency(Math.abs(v));

export interface CustomerLedgerReportData {
  customer: Customer;
  entries: CustomerLedgerEntry[];
  storeName?: string;
  storeAddress?: string;
  storePhone?: string;
}

const DEFAULT_STORE = {
  name: 'DUKANOS',
  address: 'Main Bazar Road, City 46000',
  phone: 'Tel: 0300-1234567'
};

export function buildCustomerLedgerA4(data: CustomerLedgerReportData): string {
  const c = data.customer;
  const storeName = data.storeName || DEFAULT_STORE.name;
  const storeAddress = data.storeAddress || DEFAULT_STORE.address;
  const storePhone = data.storePhone || DEFAULT_STORE.phone;

  const rows = data.entries.map(e => `
    <tr>
      <td>${formatDate(e.date)}</td>
      <td>${escapeHtml(e.description)}</td>
      <td class="num ${e.transaction_type === 'debit' ? 'dr' : ''}">${e.transaction_type === 'debit' ? money(e.amount) : '-'}</td>
      <td class="num ${e.transaction_type === 'credit' ? 'cr' : ''}">${e.transaction_type === 'credit' ? money(e.amount) : '-'}</td>
      <td class="num bold">${money(e.running_balance)} ${e.running_balance > 0 ? 'Dr' : e.running_balance < 0 ? 'Cr' : ''}</td>
    </tr>
  `).join('');

  return `<!doctype html><html><head><title>Ledger - ${escapeHtml(c.name)}</title>
<style>
  * { box-sizing: border-box; }
  body { font-family: ui-sans-serif, system-ui, sans-serif; font-size: 11px; margin: 0; padding: 40px; color: #18181B; }
  .head { display: flex; justify-content: space-between; border-bottom: 2px solid #E4E4E7; padding-bottom: 20px; margin-bottom: 24px; }
  .co-name { font-size: 20px; font-weight: 800; letter-spacing: -0.02em; }
  .co-addr { color: #71717A; font-size: 12px; margin-top: 4px; }
  .title { font-size: 16px; font-weight: 700; text-transform: uppercase; margin-bottom: 12px; }
  .info-grid { display: grid; grid-template-columns: 1fr 1fr; gap: 12px; background: #FAFAF8; border: 1px solid #E4E4E7; padding: 16px; border-radius: 8px; margin-bottom: 24px; }
  .lbl { font-size: 9px; text-transform: uppercase; color: #71717A; font-weight: 600; letter-spacing: 0.05em; margin-bottom: 2px; }
  .val { font-size: 13px; font-weight: 600; }
  .bal-box { text-align: right; }
  .bal-box .val { font-size: 16px; font-family: ui-monospace, monospace; }
  .val.dr { color: #B91C1C; }
  .val.cr { color: #065F46; }
  table { width: 100%; border-collapse: collapse; font-variant-numeric: tabular-nums; }
  th, td { padding: 8px 12px; border-bottom: 1px solid #E4E4E7; }
  thead th { background: #FAFAF8; text-align: left; font-size: 10px; color: #71717A; font-weight: 600; border-top: 1px solid #E4E4E7; border-bottom: 2px solid #E4E4E7; }
  .num { text-align: right; }
  td.dr { color: #B91C1C; }
  td.cr { color: #065F46; }
  .bold { font-weight: 700; }
  .foot { margin-top: 32px; font-size: 9px; color: #A1A1AA; text-align: center; }
</style></head><body>
  <div class="head">
    <div>
      <div class="co-name">${escapeHtml(storeName)}</div>
      <div class="co-addr">${escapeHtml(storeAddress)}<br/>${escapeHtml(storePhone)}</div>
    </div>
    <div style="text-align: right;">
      <div class="title">Customer Statement</div>
      <div>Date: ${escapeHtml(formatDate(new Date()))}</div>
    </div>
  </div>

  <div class="info-grid">
    <div>
      <div class="lbl">Customer Name</div>
      <div class="val">${escapeHtml(c.name)}</div>
      <div class="lbl" style="margin-top: 8px">Contact Info</div>
      <div class="val" style="font-weight: 400">${escapeHtml(c.phone || '-')}</div>
      ${c.address ? `<div class="val" style="font-weight: 400">${escapeHtml(c.address)}</div>` : ''}
    </div>
    <div class="bal-box">
      <div class="lbl">Closing Balance</div>
      <div class="val ${c.current_balance! > 0 ? 'dr' : c.current_balance! < 0 ? 'cr' : ''}">
        ${money(c.current_balance || 0)} 
        ${c.current_balance! > 0 ? '(Owes Us)' : c.current_balance! < 0 ? '(We Owe)' : '(Settled)'}
      </div>
    </div>
  </div>

  <table>
    <thead>
      <tr>
        <th>Date</th>
        <th>Description</th>
        <th class="num">Debit (+)</th>
        <th class="num">Credit (-)</th>
        <th class="num">Balance</th>
      </tr>
    </thead>
    <tbody>${rows}</tbody>
  </table>

  <div class="foot">Generated by DukanOS · ${escapeHtml(new Date().toLocaleString('en-PK'))}</div>
</body></html>`;
}

